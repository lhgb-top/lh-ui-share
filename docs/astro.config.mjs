// 站点部署在 https://www.lhgb.top/lhui/share/，但 Starlight 0.42.6 的 hero
// 按钮与 Astro 的 markdown 正文链接都不会自动拼 base，只有侧边栏 / 分页 /
// 资源路径由框架处理。这里用 mdast 插件在构建期给内容里以 / 开头的站内
// 链接（含图片与链接定义）补上前缀，正文写绝对路径也不必关心 base。
// Astro 7 起 Sätteri 是默认 markdown 处理器：不再支持 markdown.remarkPlugins
// （会因缺少 @astrojs/markdown-remark 直接报错），mdast 插件要通过
// processor: satteri({ mdastPlugins }) 显式传入；@astrojs/mdx 与 Starlight
// 都会复用这同一个 processor（Starlight 往其 options.mdastPlugins 追加自己的
// 插件），故对 .md 与 .mdx 内容页同时生效。
const base = '/lhui/share/';
const basePrefix = base.endsWith('/') ? base.slice(0, -1) : base;

// Sätteri 插件按节点类型注册 visitor：返回新节点表示替换，不返回表示原样保留。
// node.url 只在是站内绝对路径（以 / 开头但非协议相对的 //）时才需要补前缀。
function rewriteSiteUrl(node) {
  const url = node.url;
  if (typeof url !== 'string' || !url.startsWith('/') || url.startsWith('//')) return;
  // 根路径单独保留尾斜杠
  return { ...node, url: url === '/' ? base : basePrefix + url };
}

const basePrefixPlugin = {
  name: 'lh-base-prefix',
  link: rewriteSiteUrl,
  image: rewriteSiteUrl,
  definition: rewriteSiteUrl,
};

